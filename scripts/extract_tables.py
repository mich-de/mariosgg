#!/usr/bin/env python3
"""Export the phrase tables (text + lip-sync movie id) from mario.exe's data segment.

mario.exe is a Borland C++ program with a VROOMM overlay; its DGROUP data segment is not
overlaid, so it can be read straight from the load module.  DGROUP = segment-table entry of
kind 0 larger than 32 KiB (see scripts/unoverlay.py for the FBOV format).

Usage: scripts/extract_tables.py _source/mariosgg/mario.exe js/data/tables.js
"""
import json
import struct
import sys

# (name, DGROUP offset, record size, count) — each found as the phrase-table argument of the
# talker init call (1aec:0000) in the matching overlay.
TABLES = [
    ("menu", 0x41AE, 6, 23),
    ("intro", 0x4D34, 6, 3),
    ("checkers", 0x15C6, 6, 0x5B),
    ("dominoes", 0x2724, 16, 90),
    ("fish", 0x358C, 6, 0x57),
    ("yacht", 0x568A, 6, 0x4A),
    ("backgammon", 0x692, 6, 0x3B),
]


def dgroup(exe):
    d = open(exe, "rb").read()
    hdr = struct.unpack_from("<H", d, 8)[0] * 16
    cblp, cp = struct.unpack_from("<HH", d, 2)
    modend = (cp - 1) * 512 + (cblp or 512)
    assert d[modend:modend + 4] == b"FBOV"
    _, segtab, segcount = struct.unpack_from("<III", d, modend + 4)
    best = None
    for i in range(segcount):
        para, size, kind, low = struct.unpack_from("<4H", d, segtab + 8 * i)
        if kind == 0 and size > 0x8000:
            best = para
    return d[hdr + best * 16: hdr + best * 16 + 0x10000]


def cstr(dg, off):
    e = dg.index(b"\0", off)
    return dg[off:e].decode("latin1")


def main(exe, out):
    dg = dgroup(exe)
    res = {}
    for name, off, size, count in TABLES:
        rows = []
        for i in range(count):
            s, mv = struct.unpack_from("<HH", dg, off + size * i)
            rows.append([cstr(dg, s).strip() if s else "", mv])
        res[name] = rows
    with open(out, "w") as f:
        f.write("// Generated by scripts/extract_tables.py from mario.exe — do not edit.\n")
        f.write("export const TABLES = ")
        json.dump(res, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
